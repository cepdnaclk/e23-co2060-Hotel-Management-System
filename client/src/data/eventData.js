export function buildEventSearchText(event) {
  return [
    event.title,
    event.category,
    event.city,
    event.district,
    event.location,
    event.dateLabel,
    event.priceLabel,
    event.mood,
    event.bestFor,
    ...(event.nearHotels || []),
  ]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
}

